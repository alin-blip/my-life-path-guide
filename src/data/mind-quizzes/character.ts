const make = (
  slug: string,
  ro: string,
  en: string,
  desc_ro: string,
  desc_en: string,
  axes: MindQuiz["axes"],
  pairs: Array<{ ro: string; en: string }>,
): MindQuiz => ({
  slug,
  category: "character",
  title_ro: ro,
  title_en: en,
  description_ro: desc_ro,
  description_en: desc_en,
  instructions_ro: INSTR_RO,
  instructions_en: INSTR_EN,
  scaleLabel_ro: SCALE_RO,
  scaleLabel_en: SCALE_EN,
  scoring: SCORING,
  axes,
  questions: build(pairs),
  bands: bands(ro, en),
});

